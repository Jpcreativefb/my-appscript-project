const server = http.createServer((req, res) => {
  const url = new URL(req.url, "http://localhost");
  if (url.pathname === "/api/digit-clock") {
    res.setHeader("content-type", "application/json");
    const league = url.searchParams.get("league") || "nfl";
    const summary = structuredClone(["nba", "mlb", "nhl"].includes(league) ? require(`../tests/fixtures/digit_clock_espn_${league}.json`).summary : fixture);
    if (url.searchParams.has("event")) summary.header.competitions[0].id = url.searchParams.get("event");
    res.end(JSON.stringify(url.searchParams.has("event") ? { league, summary } : { events: [{ id: "401547417", name: "Packers at Falcons" }] }));
    return;
  }
  const file = path.resolve(root, "." + decodeURIComponent(url.pathname));
  if (!file.startsWith(root + path.sep) || !fs.existsSync(file)) { res.writeHead(404); res.end(); return; }
  res.setHeader("content-type", file.endsWith(".js") ? "text/javascript" : file.endsWith(".css") ? "text/css" : "text/html");
  res.end(fs.readFileSync(file));
});
